"""
第一章 数据自动化清洗 — 报名表脏数据清洗脚本
对应章节 项目实施: 清洗报名表中的脏数据
运行方式: python clean_registration.py

说明:
  本脚本模拟清洗校园运动会报名表中的各类脏数据，
  包括: 特殊符号、缺失值、重复录入、格式错误等。
"""

import pandas as pd
import numpy as np

print("=" * 60)
print("拯救混乱的校园数据 — 报名表清洗")
print("=" * 60)

# ========== 构建模拟报名表脏数据 ==========
raw_data = {
    '学号':   ['S001', 'S002', 'S003', 'S004', 'S005', 'S001', 'S006', 'S007'],
    '姓名':   ['张三', '李@四#', '王五', '赵六', '陈**七', '张三', '周八', '吴九'],
    '性别':   ['男', '男', None, '男', '女', '男', '女', '未知'],
    '班级':   ['高一(1)班', '高一(2)班', '高一(1)班', '高一(3)班', '高一(1)班',
               '高一(1)班', '高一(3)班', '高一(2)班'],
    '项目':   ['100米', '跳远', '铅球', '100米', '跳高', '100米', None, '铅球'],
    '手机号': ['13800001111', '13900002222', '1370000333', '13600004444',
               '1350000', '13800001111', '13800006666', None],
    '年龄':   [16, 17, 16, -3, 17, 16, 15, 16],
    '备注':   ['', '', '', '', '', '', '', '']
}

df = pd.DataFrame(raw_data)
print("\n【清洗前】原始脏数据:")
print(df)
print(f"\n总行数: {len(df)}")

# ========== 步骤 1: 去除姓名中的特殊符号 ==========
print("\n" + "." * 40)
print("步骤 1: 去除姓名中的特殊符号")
print("." * 40)
df['姓名'] = df['姓名'].str.replace(r'[@#\*]+', '', regex=True)
print("姓名列已清理完成")

# ========== 步骤 2: 处理缺失值 ==========
print("\n" + "." * 40)
print("步骤 2: 处理缺失值")
print("." * 40)
print(f"各列缺失值数量:\n{df.isnull().sum()}")
df['性别'] = df['性别'].fillna('未填写')
df['项目'] = df['项目'].fillna('待确认')
df['手机号'] = df['手机号'].fillna('未填写')
print("缺失值已填充")

# ========== 步骤 3: 修正异常值 ==========
print("\n" + "." * 40)
print("步骤 3: 修正异常值")
print("." * 40)
# 性别只能是"男"或"女"
df['性别'] = df['性别'].apply(lambda x: x if x in ['男', '女'] else '未填写')
# 年龄范围 0-120
df.loc[~df['年龄'].between(0, 120), '年龄'] = np.nan
df['年龄'] = df['年龄'].fillna(round(df['年龄'].mean(), 0)).astype(int)
print("异常值已修正")

# ========== 步骤 4: 验证手机号格式 ==========
print("\n" + "." * 40)
print("步骤 4: 验证手机号格式")
print("." * 40)
# 标记长度不正确的手机号
df['手机号_状态'] = df['手机号'].apply(
    lambda x: '格式错误' if len(str(x)) != 11 else '正常'
)
print("手机号格式验证完成")

# ========== 步骤 5: 去除重复行 ==========
print("\n" + "." * 40)
print("步骤 5: 去除重复行")
print("." * 40)
before = len(df)
df = df.drop_duplicates(subset=['姓名', '班级', '项目'], keep='first')
print(f"去重: {before} → {len(df)} (移除 {before - len(df)} 条重复)")

# ========== 步骤 6: 输出最终结果 ==========
print("\n" + "." * 40)
print("步骤 6: 输出清洗结果")
print("." * 40)
print("\n【清洗后】干净数据:")
print(df)
print(f"\n最终数据行数: {len(df)}")
print(f"清洗完成! 数据已准备就绪。")
